create table public."18_content_pipeline" (
  pipeline_id bigint generated by default as identity primary key,
  content_topic_id bigint not null unique references public."16_content_topic"(content_topic_id) on delete restrict,
  topic_key text not null unique,
  content_key text,
  stage text not null default 'PLANNING' check (stage = any (array[
    'PLANNING','PLANNED','RESEARCHING','RESEARCHED','WRITING','DRAFTED',
    'VISUAL','IMAGE_READY','QA','QA_PASS','PUBLISHING','COMPLETE','HOLD','BLOCKED'
  ])),
  planning_artifact jsonb not null default '{}'::jsonb,
  research_artifact jsonb not null default '{}'::jsonb,
  writer_artifact jsonb not null default '{}'::jsonb,
  image_manifest jsonb not null default '[]'::jsonb check (jsonb_typeof(image_manifest) = 'array'),
  qa_artifact jsonb not null default '{}'::jsonb,
  publish_artifact jsonb not null default '{}'::jsonb,
  content_id bigint references public."12_content"(content_id) on delete set null,
  production_url text,
  last_error text,
  retry_count integer not null default 0 check (retry_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);
create index "18_content_pipeline_stage_idx" on public."18_content_pipeline"(stage, updated_at, pipeline_id);

create table public."19_content_pipeline_run" (
  pipeline_run_id bigint generated by default as identity primary key,
  pipeline_id bigint not null references public."18_content_pipeline"(pipeline_id) on delete cascade,
  stage text not null,
  status text not null default 'RUNNING' check (status = any (array['RUNNING','PASS','SKIP','HOLD','BLOCKED','FAILED'])),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  summary text,
  error text,
  metadata jsonb not null default '{}'::jsonb
);
create index "19_content_pipeline_run_pipeline_idx" on public."19_content_pipeline_run"(pipeline_id, started_at desc);

